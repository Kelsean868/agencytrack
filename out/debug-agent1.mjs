import { chromium } from 'playwright';
import { newLegContext, login } from '../scripts/verification/vh/vh-helpers.mjs';
const browser = await chromium.launch();
const ctx = await newLegContext(browser);
await login(ctx.page, 'agent1');
await ctx.page.waitForTimeout(6000);
await ctx.page.screenshot({ path: 'out/debug-agent1.png', fullPage: true });
const text = await ctx.page.evaluate(() => document.body.innerText.slice(0, 2500));
console.log(text);
await browser.close();
