#!/usr/bin/env node
/**
 * sync-portfolio-import.mjs — copies the pure portfolio-import modules from
 * `src/lib/portfolioImport/` into `functions/portfolioImport/esm/`, byte for byte.
 *
 * WHY A COPY EXISTS AT ALL:
 * `firebase deploy --only functions` uploads the `functions/` directory and
 * nothing else — `firebase.json` sets `functions.source = "functions"`. Code under
 * `src/` therefore cannot reach a Cloud Function at runtime, no matter how it is
 * imported. The parser has to exist inside `functions/`.
 *
 * WHY BYTE-FOR-BYTE AND NOT A HAND-PORT:
 * this repo already has a hand-ported twin — `computePoints.js` exists in both
 * `src/lib/` and `functions/lib/` — and the two have ALREADY drifted. A hand-port
 * cannot be compared mechanically, so drift is invisible until a number is wrong.
 * A byte-identical copy can be compared in one line, which is what
 * `__tests__/functionsMirror.test.js` does, so drift fails CI instead of failing
 * a manager's persistency figure.
 *
 * The copies keep their `.js` names and their relative imports, and the directory
 * carries its own `package.json` with `"type": "module"` so Node 20 treats them as
 * ESM inside an otherwise-CommonJS functions package. `loadPortfolioImport.js`
 * reaches them with a dynamic `import()`.
 *
 * Usage:  npm run sync:portfolio-import
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..', '..');

/** The closed import graph. `oipaImportConfig.js` is a leaf; the other two import only it. */
export const MIRRORED_FILES = Object.freeze([
  'oipaImportConfig.js',
  'parseOipaExport.js',
  'buildImportPlan.js',
]);

export const SRC_DIR = join(repoRoot, 'src', 'lib', 'portfolioImport');
export const MIRROR_DIR = join(repoRoot, 'functions', 'portfolioImport', 'esm');

/** Marks the mirror directory as ESM inside the CommonJS functions package. */
export const MIRROR_PACKAGE_JSON = `${JSON.stringify(
  {
    name: 'agencytrack-portfolio-import-mirror',
    private: true,
    type: 'module',
    comment:
      'GENERATED by scripts/build/sync-portfolio-import.mjs. Do not edit these files — '
      + 'edit src/lib/portfolioImport/ and re-run `npm run sync:portfolio-import`.',
  },
  null,
  2,
)}\n`;

function sync() {
  mkdirSync(MIRROR_DIR, { recursive: true });
  writeFileSync(join(MIRROR_DIR, 'package.json'), MIRROR_PACKAGE_JSON);
  for (const name of MIRRORED_FILES) {
    writeFileSync(join(MIRROR_DIR, name), readFileSync(join(SRC_DIR, name)));
    console.log(`synced ${name}`);
  }
  console.log(`\nmirror written to functions/portfolioImport/esm/`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) sync();

export default sync;
