/**
 * Track J — Kiosk v2 restyle smoke.
 *
 * Pattern mirrors e5-1-walk's kiosk-URL-from-manager flow:
 *   1. BM signs in to the manager dashboard.
 *   2. Manager Kiosk tab generates a fresh kiosk URL.
 *   3. Fresh context opens the kiosk URL.
 *   4. Assert: shell loads, at least one restyled accent is in the DOM
 *      (text-presentation-gold OR animate-kiosk-halo-gold OR animate-kiosk-breathe),
 *      panel rotates within ~25s (welcome=15s → agentOfMonth=45s; we wait up to
 *      25s and assert the panel changes by checking the visible h1).
 *   5. 0 console errors.
 *
 * Kiosk is theme-independent (mount forces .dark + uses presentation tokens),
 * so this smoke is ONE render — not light/dark dual.
 */
import { chromium } from 'playwright';
import { readFileSync } from 'fs';
import { setupBypassSession } from './lib/walk-helpers.mjs';

function loadEnv() {
  try {
    const src = readFileSync('.env.local', 'utf8');
    src.split(/\r?\n/).forEach((line) => {
      const eq = line.indexOf('=');
      if (eq < 1) return;
      const k = line.slice(0, eq).trim();
      const v = line.slice(eq + 1).trim().replace(/^["']|["']$/g, '');
      if (k && !(k in process.env)) process.env[k] = v;
    });
  } catch { /* ignore */ }
}
loadEnv();

const args = Object.fromEntries(process.argv.slice(2).map(a => {
  const [k, v] = a.replace(/^--/, '').split('=');
  return [k, v];
}));
const URL          = args.url ?? 'http://127.0.0.1:4173';
const IS_PROD      = URL.startsWith('https://');
const BYPASS_TOKEN = process.env.VERCEL_BYPASS_TOKEN;

const BM_EMAIL = process.env.A11Y_BRANCH_MANAGER_EMAIL;
const BM_PASS  = process.env.A11Y_BRANCH_MANAGER_PASSWORD;

if (!BM_EMAIL || !BM_PASS) {
  console.error('Missing A11Y_BRANCH_MANAGER_* — kiosk smoke skipped');
  process.exit(0);
}
if (IS_PROD && !BYPASS_TOKEN) {
  console.error('Missing VERCEL_BYPASS_TOKEN for prod URL');
  process.exit(1);
}

async function login(page, email, pass) {
  await page.waitForSelector('input[type="email"]', { timeout: 30_000 });
  await page.fill('input[type="email"]', email);
  await page.fill('input[type="password"]', pass);
  await Promise.all([
    page.waitForFunction(() => !document.querySelector('input[type="email"]'), { timeout: 30_000 }),
    page.click('button[type="submit"]'),
  ]);
  await page.waitForFunction(
    () => document.body && document.body.textContent.replace(/\s+/g, '').length > 400,
    { timeout: 30_000 }
  );
  await page.waitForTimeout(1500);
}

async function newCtx() {
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1280, height: 720 } });
  if (IS_PROD) await setupBypassSession(context, URL, BYPASS_TOKEN);
  return { browser, context };
}

// ── Step 1: BM logs in + generates a kiosk URL ───────────────────────────────
const { browser: mgrBrowser, context: mgrCtx } = await newCtx();
const mgrPage = await mgrCtx.newPage();
const mgrErrors = [];
mgrPage.on('console', (m) => {
  if (m.type() !== 'error') return;
  const text = m.text();
  if (text.includes('fontshare.com')) return;
  mgrErrors.push(text);
});

await mgrPage.goto(URL, { waitUntil: 'domcontentloaded' });
await login(mgrPage, BM_EMAIL, BM_PASS);

await mgrPage.waitForTimeout(800);
const kioskNav = mgrPage.locator('[data-testid="nav-kiosk"]');
const kioskNavCount = await kioskNav.count();
if (kioskNavCount === 0) {
  console.error('Kiosk nav not visible to BM — restyle smoke cannot run');
  await mgrBrowser.close();
  process.exit(1);
}
await kioskNav.click();
await mgrPage.waitForFunction(
  () => !!document.querySelector('a[href*="/kiosk/"]'),
  { timeout: 30_000 }
).catch(async () => {
  // Some kiosk tabs use a "Generate" button before showing the link.
  const generateBtn = mgrPage.getByRole('button', { name: /generate/i });
  if (await generateBtn.count() > 0) {
    await generateBtn.first().click();
    await mgrPage.waitForFunction(
      () => !!document.querySelector('a[href*="/kiosk/"]'),
      { timeout: 30_000 }
    );
  }
});

const kioskHref = await mgrPage.locator('a[href*="/kiosk/"]').first().getAttribute('href');
if (!kioskHref) {
  console.error('No kiosk URL generated by BM tab');
  await mgrBrowser.close();
  process.exit(1);
}
const kioskUrl = kioskHref.startsWith('http') ? kioskHref : `${URL}${kioskHref}`;
console.log(`[kiosk URL acquired] (length=${kioskUrl.length})`);

// ── Step 2: open the kiosk URL in a fresh context ────────────────────────────
const { browser: kBrowser, context: kCtx } = await newCtx();
const kPage = await kCtx.newPage();
const kErrors = [];
kPage.on('console', (m) => {
  if (m.type() !== 'error') return;
  const text = m.text();
  if (text.includes('fontshare.com')) return;
  if (text.includes('Failed to load resource') && text.includes('net::ERR_FAILED')) return;
  kErrors.push(text);
});

await kPage.goto(kioskUrl, { waitUntil: 'domcontentloaded' });

// Wait for the shell to clear loading (spinner gone OR first panel visible).
await kPage.waitForFunction(
  () => {
    const spinner = document.querySelector('.animate-spin');
    const hasH1 = document.querySelectorAll('h1').length > 0;
    const hasGreeting = (document.body.textContent || '').match(/Good (Morning|Afternoon|Evening)/);
    return !spinner && (hasH1 || hasGreeting);
  },
  { timeout: 60_000 }
);
await kPage.waitForTimeout(800);

// ── Step 3: assert restyle accents in DOM ────────────────────────────────────
const initialHeadline = await kPage.evaluate(() => {
  const h1 = document.querySelector('h1');
  const greet = (document.body.textContent || '').match(/Good (Morning|Afternoon|Evening)/);
  return h1?.textContent?.trim() || (greet ? greet[0] : null);
});

// We expect EITHER (a) a visible heading from one of the panels OR
// (b) on Welcome panel: a `.animate-kiosk-breathe` brand mark.
const accentCounts = await kPage.evaluate(() => ({
  goldText:    document.querySelectorAll('.text-presentation-gold').length,
  haloGold:    document.querySelectorAll('.animate-kiosk-halo-gold').length,
  breathe:     document.querySelectorAll('.animate-kiosk-breathe').length,
  brandMark:   document.querySelectorAll('[data-testid="welcome-brand-mark"]').length,
  aomHalo:     document.querySelectorAll('[data-testid="aom-winner-halo"]').length,
  achievedCard:document.querySelectorAll('[data-testid="awards-watch-achieved-card"]').length,
}));
const accentTotal = accentCounts.goldText + accentCounts.haloGold + accentCounts.breathe;

// ── Step 4: wait for panel rotation (welcome 15s → agentOfMonth 45s) ─────────
console.log(`[panel-1] headline="${initialHeadline}"  accents=${JSON.stringify(accentCounts)}`);
const rotatedAt = Date.now();
const rotated = await kPage.waitForFunction(
  (initial) => {
    const h1 = document.querySelector('h1');
    const greet = (document.body.textContent || '').match(/Good (Morning|Afternoon|Evening)/);
    const cur = h1?.textContent?.trim() || (greet ? greet[0] : null);
    return cur && cur !== initial;
  },
  initialHeadline,
  { timeout: 30_000 }
).then(() => true).catch(() => false);
const rotationMs = Date.now() - rotatedAt;
const newHeadline = await kPage.evaluate(() => {
  const h1 = document.querySelector('h1');
  const greet = (document.body.textContent || '').match(/Good (Morning|Afternoon|Evening)/);
  return h1?.textContent?.trim() || (greet ? greet[0] : null);
});
console.log(`[panel-2] rotation=${rotated} after ${rotationMs}ms  headline="${newHeadline}"`);

const pass = (
  initialHeadline !== null &&
  accentTotal > 0 &&
  rotated &&
  newHeadline !== initialHeadline &&
  kErrors.length === 0 &&
  mgrErrors.length === 0
);

console.log('\n=== Kiosk v2 restyle smoke summary ===');
console.log(JSON.stringify({
  kioskUrlLen:  kioskUrl.length,
  initialHeadline,
  newHeadline,
  accentCounts,
  rotated,
  rotationMs,
  kErrors:   kErrors.length,
  mgrErrors: mgrErrors.length,
  pass,
}));

await kBrowser.close();
await mgrBrowser.close();
process.exit(pass ? 0 : 1);
